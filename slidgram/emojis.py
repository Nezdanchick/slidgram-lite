EMOJI_TO_JABBER = {}
for k, v in JABBER_TO_EMOJI.items():
    if v not in EMOJI_TO_JABBER:
        EMOJI_TO_JABBER[v] = k

def translate_to_unicode(text: str) -> str:
    if not text:
        return text
    for jabber, emoji in JABBER_TO_EMOJI.items():
        if jabber in text:
            text = text.replace(jabber, emoji)
    return text

def translate_to_jabber(text: str) -> str:
    if not text:
        return text
    for emoji, jabber in EMOJI_TO_JABBER.items():
        if emoji in text:
            text = text.replace(emoji, jabber)
    return text
